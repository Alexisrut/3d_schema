/**
 * Учёт отсечения по этажам при выборе лучом.
 *
 * Отсечение плоскостями уровней — операция ЧИСТО ВИЗУАЛЬНАЯ: плоскости живут
 * в рендерере, а Raycaster о них ничего не знает и продолжает попадать в
 * срезанную геометрию. Из-за этого разметка между этажами уезжала на крышу:
 * на экране её нет, но луч упирался в неё первой.
 *
 * Правило простое: из списка попаданий берём первое, которое лежит в видимом
 * диапазоне. «Первое», а не «ближайшее к середине» — потому что видимая
 * поверхность и есть та, в которую пользователь целился.
 *
 * Модуль чистый: на вход идут только отметки Y, поэтому правило проверяется
 * тестами без сцены и без three.js.
 */

/**
 * Допуск на погрешность, м.
 *
 * Луч попадает ровно в плоскость среза с точностью до ошибки округления, и
 * без запаса клик по самой кромке разреза не засчитывался бы.
 */
export const CLIP_EPS = 1e-4

/** Что-то, у чего есть точка попадания. Ровно то, что нужно от THREE.Intersection. */
export interface RayHitLike {
  point: { y: number }
}

/** Лежит ли отметка в видимом диапазоне. null с любой стороны — без ограничения. */
export function withinClip(
  y: number,
  min: number | null | undefined,
  max: number | null | undefined,
  eps = CLIP_EPS,
): boolean {
  if (min !== null && min !== undefined && y < min - eps) return false
  if (max !== null && max !== undefined && y > max + eps) return false
  return true
}

/**
 * Первое попадание в видимом диапазоне.
 *
 * Порядок списка сохраняется как есть: three.js отдаёт пересечения по
 * возрастанию расстояния, и пересортировка сломала бы смысл «первое видимое».
 * Когда отсечение не задано, функция возвращает hits[0] — то же, что было до
 * её появления.
 */
export function pickWithinClip<T extends RayHitLike>(
  hits: readonly T[],
  min: number | null | undefined,
  max: number | null | undefined,
  eps = CLIP_EPS,
): T | null {
  for (const hit of hits) {
    if (withinClip(hit.point.y, min, max, eps)) return hit
  }
  return null
}
